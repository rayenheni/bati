  const textNodes = [];
  const attrNodes = [];
  let current = 'fr';

  function has(o, k) { return Object.prototype.hasOwnProperty.call(o, k); }

  function collect() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let n;
    while ((n = walker.nextNode())) {
      if (n.parentElement && n.parentElement.closest('script, style')) continue;
      const raw = n.nodeValue;
      const key = raw.trim();
      if (!key || !has(FR_TO_AR, key)) continue;
      textNodes.push({ node: n, raw: raw, key: key, ar: FR_TO_AR[key] });
    }
    const names = ['alt', 'placeholder', 'aria-label', 'title'];
    document.body.querySelectorAll('*').forEach(el => {
      names.forEach(name => {
        const fr = el.getAttribute(name);
        if (fr && has(ATTR, fr)) attrNodes.push({ el: el, name: name, fr: fr, ar: ATTR[fr] });
      });
    });
  }

  function setMeta(name, value, property) {
    const sel = property ? 'meta[property="' + name + '"]' : 'meta[name="' + name + '"]';
    const el = document.querySelector(sel);
    if (el) el.setAttribute('content', value);
  }

  function apply(lang) {
    current = (lang === 'ar') ? 'ar' : 'fr';
    const arabic = current === 'ar';
    document.documentElement.lang = current;
    document.documentElement.dir = arabic ? 'rtl' : 'ltr';

    textNodes.forEach(x => { x.node.nodeValue = x.raw.replace(x.key, arabic ? x.ar : x.key); });
    attrNodes.forEach(x => { x.el.setAttribute(x.name, arabic ? x.ar : x.fr); });

    const m = META[current];
    const pageTitle = document.querySelector('title[data-fr][data-ar]');
    document.title = pageTitle ? pageTitle.getAttribute('data-' + current) : m.title;
    const descriptionMeta = document.querySelector('meta[name="description"]');
    const ogTitleMeta = document.querySelector('meta[property="og:title"]');
    const ogDescriptionMeta = document.querySelector('meta[property="og:description"]');
    setMeta('description', (descriptionMeta && descriptionMeta.getAttribute('data-' + current)) || m.description);
    setMeta('og:title', (ogTitleMeta && ogTitleMeta.getAttribute('data-' + current)) || m.ogTitle, true);
    setMeta('og:description', (ogDescriptionMeta && ogDescriptionMeta.getAttribute('data-' + current)) || m.ogDescription, true);
    const ogLocale = document.querySelector('meta[property="og:locale"]');
    if (ogLocale) ogLocale.setAttribute('content', arabic ? 'ar_TN' : 'fr_TN');
    const ogAlt = document.querySelector('meta[property="og:locale:alternate"]');
    if (ogAlt) ogAlt.setAttribute('content', arabic ? 'fr_TN' : 'ar_TN');

    document.querySelectorAll('.lang-btn').forEach(btn => {
      const active = btn.dataset.lang === current;
      btn.classList.toggle('is-active', active);
      btn.setAttribute('aria-pressed', String(active));
    });

    try { localStorage.setItem('bati-lang', current); } catch (e) {}
    try {
      const u = new URL(location.href);
      if (arabic) u.searchParams.set('lang', 'ar'); else u.searchParams.delete('lang');
      history.replaceState(null, '', u.pathname + u.search + u.hash);
    } catch (e) {}

    window.I18N.lang = current;
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: current } }));
  }

  function initial() {
    try {
      const q = new URLSearchParams(location.search).get('lang');
      if (q === 'ar' || q === 'fr') return q;
    } catch (e) {}
    try {
      const saved = localStorage.getItem('bati-lang');
      if (saved === 'ar' || saved === 'fr') return saved;
    } catch (e) {}
    return 'fr';
  }

